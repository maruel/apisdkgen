// Standard package manifests for generated versioned SDKs.

package apisdkgen

import (
	_ "embed"
	"encoding/json"
	"fmt"
	"path/filepath"
	"slices"
	"strings"
)

// kotlinDependencyData pins the generated package and its compiler/runtime tests together.
//
//go:embed kotlin-dependencies.json
var kotlinDependencyData []byte

type kotlinDependencies struct {
	Kotlin        string `json:"kotlin"`
	OkHTTP        string `json:"okhttp"`
	Okio          string `json:"okio"`
	Coroutines    string `json:"coroutines"`
	Serialization string `json:"serialization"`
}

type typeScriptPackage struct {
	Name    string            `json:"name"`
	Private bool              `json:"private"`
	Type    string            `json:"type"`
	Exports map[string]string `json:"exports"`
}

func generateManifests(api *API, versions []Version, langs []Language, out *preparedOutput) error {
	if slices.Contains(langs, TypeScript) {
		if err := out.write(filepath.Join(api.outputDir, "ts", ".gitignore"), "/node_modules/\n"); err != nil {
			return err
		}
		exports := make(map[string]string, len(versions))
		for _, version := range versions {
			exports["./"+version.name+"/*"] = "./" + version.name + "/*.ts"
		}
		pkg := typeScriptPackage{Name: strings.ToLower(api.name), Private: true, Type: "module", Exports: exports}
		data, err := json.MarshalIndent(pkg, "", "  ")
		if err != nil {
			return err
		}
		if err := out.write(filepath.Join(api.outputDir, "ts", "package.json"), string(data)+"\n"); err != nil {
			return err
		}
		if err := out.write(filepath.Join(api.outputDir, "ts", "tsconfig.json"), `{
  "compilerOptions": {
    "target": "ES2022",
    "module": "ESNext",
    "moduleResolution": "bundler",
    "strict": true,
    "noEmit": true,
    "lib": ["ES2022", "DOM"]
  },
  "include": ["v*/*.ts"]
}
`); err != nil {
			return err
		}
	}
	if slices.Contains(langs, Kotlin) {
		var deps kotlinDependencies
		if err := json.Unmarshal(kotlinDependencyData, &deps); err != nil {
			return fmt.Errorf("kotlin dependency metadata: %w", err)
		}
		if err := out.write(filepath.Join(api.outputDir, "kotlin", ".gitignore"), "/.gradle/\n/.kotlin/\n/build/\n"); err != nil {
			return err
		}
		if err := out.write(filepath.Join(api.outputDir, "kotlin", "settings.gradle.kts"), fmt.Sprintf(`// Code generated by apisdkgen. DO NOT EDIT.
pluginManagement {
    repositories {
        gradlePluginPortal()
        mavenCentral()
    }
    plugins {
        kotlin("jvm") version "%[1]s"
        kotlin("plugin.serialization") version "%[1]s"
    }
}

dependencyResolutionManagement {
    repositories {
        mavenCentral()
    }
}

rootProject.name = %[2]q
`, deps.Kotlin, api.name)); err != nil {
			return err
		}
		if err := out.write(filepath.Join(api.outputDir, "kotlin", "build.gradle.kts"), fmt.Sprintf(`// Code generated by apisdkgen. DO NOT EDIT.
plugins {
    `+"`java-library`"+`
    kotlin("jvm")
    kotlin("plugin.serialization")
}

kotlin {
    jvmToolchain(21)
}

dependencies {
    api("com.squareup.okhttp3:okhttp:%[1]s")
    implementation("com.squareup.okhttp3:okhttp-sse:%[1]s")
    api("org.jetbrains.kotlinx:kotlinx-serialization-json:%[2]s")
    api("org.jetbrains.kotlinx:kotlinx-coroutines-core:%[3]s")
}
`, deps.OkHTTP, deps.Serialization, deps.Coroutines)); err != nil {
			return err
		}
	}
	if slices.Contains(langs, Swift) {
		if err := out.write(filepath.Join(api.outputDir, "swift", ".gitignore"), "/.build/\n/.swiftpm/\n"); err != nil {
			return err
		}
		var b strings.Builder
		b.WriteString("// swift-tools-version: 5.9\n// Code generated by apisdkgen. DO NOT EDIT.\nimport PackageDescription\n\nlet package = Package(\n")
		fmt.Fprintf(&b, "    name: %q,\n", api.name)
		b.WriteString("    platforms: [.macOS(.v13), .iOS(.v16)],\n    products: [\n")
		for _, version := range versions {
			name := api.name + strings.ToUpper(version.name)
			fmt.Fprintf(&b, "        .library(name: %q, targets: [%q]),\n", name, name)
		}
		b.WriteString("    ],\n    targets: [\n")
		for _, version := range versions {
			name := api.name + strings.ToUpper(version.name)
			fmt.Fprintf(&b, "        .target(name: %q),\n", name)
		}
		b.WriteString("    ]\n)\n")
		if err := out.write(filepath.Join(api.outputDir, "swift", "Package.swift"), b.String()); err != nil {
			return err
		}
	}
	return nil
}
