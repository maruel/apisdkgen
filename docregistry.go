// generateMarkdownDoc generates an API reference from the route table.
func (d *docRegistry[C]) generateMarkdownDoc(path string, out *preparedOutput) error {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\n", d.cfg.APIDocTitle)
	b.WriteString("<!-- Code generated by gen-api-sdk; DO NOT EDIT. -->\n\n")
	if d.cfg.APIDocIntro != "" {
		b.WriteString(d.cfg.APIDocIntro)
		b.WriteString("\n\n")
	}
	b.WriteString("Type notation: `JSONValue` means any valid JSON value.\n")

	groups := docGroupRoutes(d.cfg.Routes)

	// Route tables.
	for _, g := range groups {
		fmt.Fprintf(&b, "\n## %s\n\n", g.name)
		b.WriteString("| Method | Path | Description | Request | Response |\n")
		b.WriteString("|--------|------|-------------|---------|----------|\n")
		for i := range g.routes {
			r := &g.routes[i]
			req := ""
			if r.Req != nil {
				req = "`" + strings.ReplaceAll(routeJSONType(r.Req, false, TypeScript), "|", "\\|") + "`"
			}
			if r.Query != nil {
				if req != "" {
					req += "<br>"
				}
				req += "Query: `" + r.Query.Name() + "Query`"
			}
			resp := "`" + strings.ReplaceAll(routeJSONType(r.Resp, r.IsArray, TypeScript), "|", "\\|") + "`"
			if r.IsSSE {
				resp += " SSE"
				if len(r.SSEEvents) > 0 {
					named := make([]string, 0, len(r.SSEEvents))
					for j := range r.SSEEvents {
						e := &r.SSEEvents[j]
						name := "`" + e.Name + "`"
						if e.Resp != nil {
							name += " (`" + e.Resp.Name() + "`)"
						}
						named = append(named, name)
					}
					resp += "<br>Named events: " + strings.Join(named, ", ")
				}
			}
			fmt.Fprintf(&b, "| %s | `%s` | %s | %s | %s |\n", r.Method, r.Path, r.Doc, req, resp)
		}
	}

	seenQueries := map[reflect.Type]struct{}{}
	for _, r := range d.cfg.Routes {
		if r.Query == nil {
			continue
		}
		if _, ok := seenQueries[r.Query]; ok {
			continue
		}
		seenQueries[r.Query] = struct{}{}
		fields, err := routeQueryFields(d, &r)
		if err != nil {
			return err
		}
		fmt.Fprintf(&b, "\n### %sQuery parameters\n\n| Parameter | Type | Required |\n|-----------|------|----------|\n", r.Query.Name())
		for _, f := range fields {
			_, opts := parseJSONTag(f.field.Tag.Get("json"))
			typ, err := goTypeToDocValue(d.cfg, f.field.Type, false)
			if err != nil {
				return err
			}
			typ = strings.TrimSuffix(typ, " | null")
			required := "yes"
			if f.field.Type.Kind() == reflect.Pointer || slices.Contains(opts, "omitempty") || slices.Contains(opts, "omitzero") {
				required = ""
			}
			fmt.Fprintf(&b, "| `%s` | `%s` | %s |\n", f.name, strings.ReplaceAll(typ, "|", "\\|"), required)
		}
	}

	// Errors section.
	b.WriteString("\n## Errors\n\n")
	if d.cfg.ErrorDoc != "" {
		b.WriteString(d.cfg.ErrorDoc)
		b.WriteString("\n\n")
	} else {
		b.WriteString("All errors return:\n\n")
		b.WriteString("```json\n")
		b.WriteString("{\n")
		b.WriteString("  \"error\": { \"code\": \"<CODE>\", \"message\": \"...\" },\n")
		b.WriteString("  \"details\": { ... }\n")
		b.WriteString("}\n")
		b.WriteString("```\n\n")
	}
	b.WriteString("| HTTP | Code |\n")
	b.WriteString("|------|------|\n")
	for _, e := range d.cfg.ErrorCodes {
		fmt.Fprintf(&b, "| %d | `%s` |\n", e.Status, e.Code)
	}

	// Types section.
	b.WriteString("\n## Types\n")
	for i := range d.aliases {
		d.writeDocAlias(&b, &d.aliases[i])
	}
	seeds := routeSeedTypes(d.cfg)
	if d.cfg.DocumentExtraSeeds {
		seeds = sdkSeedTypes(d.cfg)
	}
	// Discover documented types in stable order, including cyclic references.
	types, err := walkSDKTypes(d.cfg, seeds)
	if err != nil {
		return err
	}
	for _, t := range types {
		if t.Kind() == reflect.Slice || t.Kind() == reflect.Map {
			if jsonByteSlice(t) {
				fmt.Fprintf(&b, "\n### %s\n\n`type %s = base64 string`\n", t.Name(), t.Name())
				continue
			}
			elem, err := goTypeToDoc(d.cfg, t.Elem())
			if err != nil {
				return err
			}
			if strings.Contains(elem, " | ") {
				elem = "(" + elem + ")"
			}
			typ := elem + "[]"
			if t.Kind() == reflect.Map {
				key, err := goTypeToDoc(d.cfg, t.Key())
				if err != nil {
					return err
				}
				typ = "Record<" + key + ", " + elem + ">"
			}
			fmt.Fprintf(&b, "\n### %s\n\n`type %s = %s`\n", t.Name(), t.Name(), typ)
			continue
		}
		if t.Kind() != reflect.Struct {
			continue
		}
		if err := d.writeDocType(&b, t); err != nil {
			return err
		}
	}

	return out.write(path, b.String())
}

func (d *docRegistry[C]) writeDocAlias(b *strings.Builder, a *aliasInfo) {
	if len(a.constants) == 0 {
		return
	}
	fmt.Fprintf(b, "\n### %s\n\n", a.name)
	if typeDoc := d.typeDoc[a.name]; typeDoc != "" {
		fmt.Fprintf(b, "%s\n\n", typeDoc)
	}
	b.WriteString("| Value | Description |\n")
	b.WriteString("|-------|-------------|\n")
	for _, c := range a.constants {
		fmt.Fprintf(b, "| `%s` | %s |\n", c.value, enumValueDescription(c))
	}
}

func enumValueDescription(c aliasConstant) string {
	return strings.ReplaceAll(strings.Join(strings.Fields(c.doc), " "), "|", `\|`)
}

func (d *docRegistry[C]) writeDocType(b *strings.Builder, t reflect.Type) error {
	fmt.Fprintf(b, "\n### %s\n\n", t.Name())
	if typeDoc := d.typeDoc[t.Name()]; typeDoc != "" {
		fmt.Fprintf(b, "%s\n\n", typeDoc)
	}
	b.WriteString("| Field | Type | Description | Required |\n")
	b.WriteString("|-------|------|-------------|----------|\n")
	fields, err := jsonFields(d.cfg, t)
	if err != nil {
		return err
	}
	for _, f := range fields {
		sf := f.field
		jsonName, opts := parseJSONTag(sf.Tag.Get("json"))
		if jsonName == "" {
			jsonName = sf.Name
		}
		optional := jsonOmittable(sf.Type, opts)
		typeName, err := goTypeToDocValue(d.cfg, sf.Type, !optional || jsonThreeState(d.cfg, sf.Type, opts))
		if err != nil {
			return fmt.Errorf("%s.%s: %w", t.Name(), jsonName, err)
		}
		req := "yes"
		if optional {
			req = ""
		}
		fieldDoc := ""
		if fdocs, ok := d.fieldDoc[f.owner.Name()]; ok {
			fieldDoc = fdocs[sf.Name]
		}
		if name := sf.Tag.Get("query"); name != "" && name != "-" {
			if fieldDoc != "" {
				fieldDoc += "<br>"
			}
			fieldDoc += "Query parameter: `" + name + "`."
		}
		fmt.Fprintf(b, "| `%s` | `%s` | %s | %s |\n", jsonName, strings.ReplaceAll(typeName, "|", "\\|"), fieldDoc, req)
	}
	return nil
}

// goTypeToSwift maps a Go reflect.Type to its Swift type string.
func (d *docRegistry[C]) goTypeToSwift(t reflect.Type) (string, error) {
	return d.goTypeToSwiftValue(t, false)
}

func (d *docRegistry[C]) goTypeToSwiftValue(t reflect.Type, nullable bool) (string, error) {
	if t.Kind() == reflect.Pointer {
		inner, err := d.goTypeToSwiftValue(t.Elem(), true)
		if err != nil {
			return "", err
		}
		if nullable && !strings.HasSuffix(inner, "?") {
			inner += "?"
		}
		return inner, nil
	}
	if nullable && (t.Kind() == reflect.Map || t.Kind() == reflect.Slice) {
		inner, err := d.goTypeToSwiftValue(t, false)
		if err != nil {
			return "", err
		}
		return inner + "?", nil
	}
	if m := lookupSpecial(d.cfg, t); m != nil {
		return m.SwiftType, nil
	}
	if jsonByteSlice(t) {
		return "Data", nil
	}

	if _, ok := d.aliasNames[t.Name()]; ok {
		return t.Name(), nil
	}
	switch t.Kind() {
	case reflect.String:
		return "String", nil
	case reflect.Int, reflect.Int32, reflect.Int64, reflect.Uint64:
		return "Int", nil
	case reflect.Float64:
		return "Double", nil
	case reflect.Bool:
		return "Bool", nil
	case reflect.Slice:
		if isSDKPkg(d.cfg, t.PkgPath()) {
			return t.Name(), nil // Named slice.
		}
		e, err := d.goTypeToSwiftValue(t.Elem(), true)
		if err != nil {
			return "", err
		}
		return "[" + e + "]", nil
	case reflect.Map:
		if t.Key().Kind() != reflect.String {
			return "", fmt.Errorf("generated Swift JSON maps require string keys: %s", t)
		}
		if isSDKPkg(d.cfg, t.PkgPath()) {
			return t.Name(), nil
		}
		k, err := d.goTypeToSwift(t.Key())
		if err != nil {
			return "", err
		}
		if k != "String" {
			return "", fmt.Errorf("generated Swift JSON maps require string keys: %s maps to %s", t, k)
		}
		v, err := d.goTypeToSwiftValue(t.Elem(), true)
		if err != nil {
			return "", err
		}
		return "[" + k + ": " + v + "]", nil
	case reflect.Struct:
		return t.Name(), nil
	default:
		return "", fmt.Errorf("goTypeToSwift: unhandled kind %s for %s", t.Kind(), t)
	}
}

// emitSwiftStruct writes a public Codable struct to b.
func (d *docRegistry[C]) emitSwiftStruct(b *strings.Builder, t reflect.Type) error {
	return d.emitSwiftStructVariant(b, t, false)
}

func (d *docRegistry[C]) emitSwiftStructVariant(b *strings.Builder, t reflect.Type, query bool) error {
	if doc := d.typeDoc[t.Name()]; doc != "" {
		b.WriteString(formatSwiftDoc(doc, ""))
	}
	name := t.Name()
	if query {
		name += "Query"
	}
	fmt.Fprintf(b, "public struct %s: Codable {\n", name)
	var swiftFields []swiftField
	hasRequiredNullable := false
	var codingKeys []string
	needCodingKeys := false
	fields, err := jsonFields(d.cfg, t)
	if err != nil {
		return err
	}
	names := make(map[string]struct{}, len(fields))
	for _, f := range fields {
		sf := f.field
		jsonName, opts := parseJSONTag(sf.Tag.Get("json"))
		if jsonName == "" {
			jsonName = sf.Name
		}
		omit := jsonOmittable(sf.Type, opts)
		isPtr := sf.Type.Kind() == reflect.Pointer
		swiftType, err := d.goTypeToSwift(sf.Type)
		if err != nil {
			return fmt.Errorf("%s.%s: %w", name, jsonName, err)
		}
		optional := omit
		if query {
			optional = isPtr || slices.Contains(opts, "omitempty") || slices.Contains(opts, "omitzero")
		}
		nullable := jsonNilable(sf.Type)
		if base, ok := strings.CutSuffix(swiftType, "?"); ok {
			swiftType = base
			nullable = true
		}
		presence := !query && jsonThreeState(d.cfg, sf.Type, opts)
		if !query && (presence || (nullable && !optional)) {
			hasRequiredNullable = true
		}
		rawSwiftName := swiftPropertyName(sf.Name, jsonName)
		if !isIdentifier(rawSwiftName) {
			return fmt.Errorf("invalid generated Swift property name %q for %s.%s", rawSwiftName, t, sf.Name)
		}
		if _, ok := names[rawSwiftName]; ok {
			return fmt.Errorf("duplicate generated Swift property name %q in %s", rawSwiftName, t)
		}
		names[rawSwiftName] = struct{}{}
		swiftName := swiftEscapeIdent(rawSwiftName)
		if rawSwiftName == jsonName {
			codingKeys = append(codingKeys, fmt.Sprintf("        case %s\n", swiftEscapeIdent(rawSwiftName)))
		} else {
			needCodingKeys = true
			codingKeys = append(codingKeys, fmt.Sprintf("        case %s = %q\n", swiftEscapeIdent(rawSwiftName), jsonName))
		}

		if fdocs, ok := d.fieldDoc[f.owner.Name()]; ok {
			if fdoc := fdocs[sf.Name]; fdoc != "" {
				b.WriteString(formatSwiftDoc(fdoc, "    "))
			}
		}
		swiftFields = append(swiftFields, swiftField{swiftName, swiftType, optional, nullable, presence})
		switch {
		case presence:
			fmt.Fprintf(b, "    public let %s: JSONPresence<%s>\n", swiftName, swiftType)
		case optional || nullable:
			fmt.Fprintf(b, "    public let %s: %s?\n", swiftName, swiftType)
		default:
			fmt.Fprintf(b, "    public let %s: %s\n", swiftName, swiftType)
		}
	}
	if needCodingKeys || hasRequiredNullable {
		b.WriteString("\n    private enum CodingKeys: String, CodingKey {\n")
		for _, key := range codingKeys {
			b.WriteString(key)
		}
		b.WriteString("    }\n")
	}
	{
		b.WriteString("\n    public init(")
		for i, f := range swiftFields {
			if i > 0 {
				b.WriteString(", ")
			}
			if f.presence {
				fmt.Fprintf(b, "%s: JSONPresence<%s> = .missing", f.name, f.typ)
			} else {
				fmt.Fprintf(b, "%s: %s", f.name, f.typ)
				if f.optional || f.nullable {
					b.WriteString("?")
				}
				if f.optional {
					b.WriteString(" = nil")
				}
			}
		}
		b.WriteString(") {\n")
		for _, f := range swiftFields {
			fmt.Fprintf(b, "        self.%s = %s\n", f.name, f.name)
		}
		b.WriteString("    }\n")
	}
	if hasRequiredNullable {
		b.WriteString("\n    public init(from decoder: Decoder) throws {\n        let c = try decoder.container(keyedBy: Self.CodingKeys.self)\n")
		for _, f := range swiftFields {
			switch {
			case f.presence:
				fmt.Fprintf(b, "        if !c.contains(.%s) { self.%s = .missing } else if try c.decodeNil(forKey: .%s) { self.%s = .null } else { self.%s = .value(try c.decode(%s.self, forKey: .%s)) }\n", f.name, f.name, f.name, f.name, f.name, f.typ, f.name)
			case f.optional:
				fmt.Fprintf(b, "        self.%s = try c.decodeIfPresent(%s.self, forKey: .%s)\n", f.name, f.typ, f.name)
			case f.nullable:
				fmt.Fprintf(b, "        self.%s = try c.decode(%s?.self, forKey: .%s)\n", f.name, f.typ, f.name)
			default:
				fmt.Fprintf(b, "        self.%s = try c.decode(%s.self, forKey: .%s)\n", f.name, f.typ, f.name)
			}
		}
		b.WriteString("    }\n\n    public func encode(to encoder: Encoder) throws {\n        var c = encoder.container(keyedBy: Self.CodingKeys.self)\n")
		for _, f := range swiftFields {
			if f.presence {
				fmt.Fprintf(b, "        switch self.%s { case .missing: break; case .null: try c.encodeNil(forKey: .%s); case .value(let value): try c.encode(value, forKey: .%s) }\n", f.name, f.name, f.name)
				continue
			}
			method := "encode"
			if f.optional {
				method = "encodeIfPresent"
			}
			fmt.Fprintf(b, "        try c.%s(self.%s, forKey: .%s)\n", method, f.name, f.name)
		}
		b.WriteString("    }\n")
	}
	b.WriteString("}\n")
	return nil
}

func (d *docRegistry[C]) writeSwiftTypes(outDir string, out *preparedOutput) error {
	var b strings.Builder
	b.WriteString("// Code generated by gen-api-sdk. DO NOT EDIT.\nimport Foundation\n\n")
	b.WriteString("/// ISO 8601 timestamp string (e.g. \"2026-04-13T12:00:00Z\").\n")
	b.WriteString("public typealias ISOTimestamp = String\n\n")
	b.WriteString(`/// A JSON field that may be omitted, null, or a value.
public enum JSONPresence<Value: Codable>: Codable {
    case missing
    case null
    case value(Value)

    public init(from decoder: Decoder) throws {
        let container = try decoder.singleValueContainer()
        self = container.decodeNil() ? .null : .value(try container.decode(Value.self))
    }

    public func encode(to encoder: Encoder) throws {
        var container = encoder.singleValueContainer()
        switch self {
        case .missing: throw EncodingError.invalidValue(self, .init(codingPath: encoder.codingPath, debugDescription: "Missing fields must be omitted"))
        case .null: try container.encodeNil()
        case .value(let value): try container.encode(value)
        }
    }
}

`)

	// JSONValue: a Codable enum for arbitrary JSON (used for json.RawMessage / map[string]any fields).
	b.WriteString(`/// A Codable representation of an arbitrary JSON value.
public enum JSONValue: Codable, Equatable {
    case string(String)
    case number(Double)
    case bool(Bool)
    case object([String: JSONValue])
    case array([JSONValue])
    case null

    public init(from decoder: Decoder) throws {
        let c = try decoder.singleValueContainer()
        if c.decodeNil() { self = .null; return }
        if let v = try? c.decode(Bool.self) { self = .bool(v); return }
        if let v = try? c.decode(Double.self) { self = .number(v); return }
        if let v = try? c.decode(String.self) { self = .string(v); return }
        if let v = try? c.decode([String: JSONValue].self) { self = .object(v); return }
        if let v = try? c.decode([JSONValue].self) { self = .array(v); return }
        throw DecodingError.dataCorrupted(.init(codingPath: decoder.codingPath, debugDescription: "Unknown JSON value"))
    }

    public func encode(to encoder: Encoder) throws {
        var c = encoder.singleValueContainer()
        switch self {
        case .string(let v): try c.encode(v)
        case .number(let v): try c.encode(v)
        case .bool(let v): try c.encode(v)
        case .object(let v): try c.encode(v)
        case .array(let v): try c.encode(v)
        case .null: try c.encodeNil()
        }
    }
}
`)

	// Structs with static cases for exhaustive switching.
	for i := range d.aliases {
		a := &d.aliases[i]
		b.WriteString("\n")
		// Struct declaration.
		fmt.Fprintf(&b, "public struct %s: Codable, Equatable, Hashable {\n", a.name)
		b.WriteString("    public let value: String\n\n")
		b.WriteString("    public init(_ value: String) { self.value = value }\n\n")
		// Known values.
		for _, c := range a.constants {
			fmt.Fprintf(&b, "    public static let %s = %s(%q)\n", a.shortName(c), a.name, c.value)
		}
		b.WriteString("\n")
		// Catch-all for forward compatibility.
		fmt.Fprintf(&b, "    public static func other(_ value: String) -> %s { %s(value) }\n\n", a.name, a.name)
		// Codable: encode/decode as a plain string.
		b.WriteString("    public init(from decoder: Decoder) throws {\n")
		b.WriteString("        let c = try decoder.singleValueContainer()\n")
		b.WriteString("        value = try c.decode(String.self)\n")
		b.WriteString("    }\n\n")
		b.WriteString("    public func encode(to encoder: Encoder) throws {\n")
		b.WriteString("        var c = encoder.singleValueContainer()\n")
		b.WriteString("        try c.encode(value)\n")
		b.WriteString("    }\n")
		b.WriteString("}\n")
	}
	if len(d.cfg.ErrorCodes) == 0 {
		b.WriteString("\npublic enum ErrorCodes {\n}\n")
	}

	// Structs.
	swStructs, err := d.discoverSwiftStructs()
	if err != nil {
		return err
	}

	// Named container type aliases.
	containers, err := collectNamedContainers(d.cfg)
	if err != nil {
		return err
	}
	for _, ns := range containers {
		b.WriteString("\n")
		if doc := d.typeDoc[ns.Name()]; doc != "" {
			b.WriteString(formatSwiftDoc(doc, ""))
		}
		if jsonByteSlice(ns) {
			fmt.Fprintf(&b, "public typealias %s = Data\n", ns.Name())
			continue
		}
		swElem, err := d.goTypeToSwiftValue(ns.Elem(), true)
		if err != nil {
			return fmt.Errorf("%s: %w", ns.Name(), err)
		}
		if ns.Kind() == reflect.Map {
			if ns.Key().Kind() != reflect.String {
				return fmt.Errorf("generated Swift JSON maps require string keys: %s", ns)
			}
			key, err := d.goTypeToSwift(ns.Key())
			if err != nil {
				return err
			}
			if key != "String" {
				return fmt.Errorf("generated Swift JSON maps require string keys: %s maps to %s", ns, key)
			}
			fmt.Fprintf(&b, "public typealias %s = [%s: %s]\n", ns.Name(), key, swElem)
		} else {
			fmt.Fprintf(&b, "public typealias %s = [%s]\n", ns.Name(), swElem)
		}
	}

	for _, ks := range swStructs {
		b.WriteString("\n")
		if ks.comment != "" {
			fmt.Fprintf(&b, "// %s\n\n", ks.comment)
		}
		if err := d.emitSwiftStruct(&b, ks.Type); err != nil {
			return err
		}
	}

	queryTypes := map[reflect.Type]struct{}{}
	for _, r := range d.cfg.Routes {
		if _, seen := queryTypes[r.Query]; r.Query != nil && !seen {
			queryTypes[r.Query] = struct{}{}
			b.WriteString("\n")
			if err := d.emitSwiftStructVariant(&b, r.Query, true); err != nil {
				return err
			}
		}
	}
	return out.write(filepath.Join(outDir, "Types.swift"), b.String())
}

// generateSwift generates Types.swift and ApiClient.swift in outDir.
func (d *docRegistry[C]) generateSwift(outDir string, out *preparedOutput) error {
	if err := d.writeSwiftTypes(outDir, out); err != nil {
		return err
	}
	return d.writeSwiftClient(outDir, out)
}

type jsonField struct {
	field reflect.StructField
	owner reflect.Type
	index []int
}

type jsonFieldCandidate struct {
	jsonField

	name   string
	tagged bool
}

type jsonFieldChoice struct {
	index    int
	conflict bool
}

// compareJSONFieldPriority orders candidates by encoding/json dominance.
func compareJSONFieldPriority(a, b jsonFieldCandidate) int {
	if n := cmp.Compare(len(a.index), len(b.index)); n != 0 {
		return n
	}
	if a.tagged == b.tagged {
		return 0
	}
	if a.tagged {
		return -1
	}
	return 1
}

// jsonFields applies encoding/json's embedded-field name precedence. Embedded
// pointers are rejected because their promoted fields may all be absent.
func jsonFields[C ~string](cfg *apispec.Config[C], t reflect.Type) ([]jsonField, error) {
	var candidates []jsonFieldCandidate
	seen := map[reflect.Type]struct{}{t: {}}
	var walk func(reflect.Type, []int) error
	walk = func(owner reflect.Type, parent []int) error {
		for sf := range owner.Fields() {
			index := append(slices.Clone(parent), sf.Index...)
			base := sf.Type
			if base.Kind() == reflect.Pointer {
				base = base.Elem()
			}
			if sf.Tag.Get("json") == "-" || (!sf.IsExported() && (!sf.Anonymous || base.Kind() != reflect.Struct)) {
				continue
			}
			name, opts := parseJSONTag(sf.Tag.Get("json"))
			if slices.Contains(opts, "string") {
				return fmt.Errorf("%s.%s: json option string is not supported; use an explicit string wire field", owner, sf.Name)
			}
			tagged := name != ""
			if sf.Anonymous && name == "" && base.Kind() == reflect.Struct {
				if sf.Type.Kind() == reflect.Pointer {
					return fmt.Errorf("%s.%s: embedded pointer fields may be absent from JSON; embed by value or give the field a JSON name", owner, sf.Name)
				}
				if !isSDKPkg(cfg, base.PkgPath()) {
					return fmt.Errorf("%s.%s: embedded struct package %q is not an SDK package; add it to SDKPackagePaths or give the field a JSON name", owner, sf.Name, base.PkgPath())
				}
				if _, ok := seen[base]; !ok {
					seen[base] = struct{}{}
					if err := walk(base, index); err != nil {
						return err
					}
					delete(seen, base)
				}
				continue
			}
			if name == "" {
				name = sf.Name
			}
			candidates = append(candidates, jsonFieldCandidate{jsonField{sf, owner, index}, name, tagged})
		}
		return nil
	}
	if err := walk(t, nil); err != nil {
		return nil, err
	}

	// At the shallowest depth, an explicitly tagged field wins. Equal-priority
	// fields conflict, so encoding/json omits that name entirely.
	best := make(map[string]jsonFieldChoice, len(candidates))
	for i, field := range candidates {
		prior, ok := best[field.name]
		if !ok {
			best[field.name] = jsonFieldChoice{index: i}
			continue
		}
		switch compareJSONFieldPriority(field, candidates[prior.index]) {
		case -1:
			best[field.name] = jsonFieldChoice{index: i}
		case 0:
			prior.conflict = true
			best[field.name] = prior
		}
	}
	fields := make([]jsonField, 0, len(best))
	for i, field := range candidates {
		if selected := best[field.name]; selected.index == i && !selected.conflict {
			fields = append(fields, field.jsonField)
		}
	}
	return fields, nil
}

// snakeToPascal converts SCREAMING_SNAKE_CASE to PascalCase ("BAD_REQUEST" → "BadRequest").
func snakeToPascal(s string) string {
	parts := strings.Split(s, "_")
	for i, p := range parts {
		lower := strings.ToLower(p)
		if lower != "" {
			parts[i] = strings.ToUpper(lower[:1]) + lower[1:]
		}
	}
	return strings.Join(parts, "")
}

func kotlinPropertyName(fieldName, jsonName string) string {
	if isIdentifier(jsonName) {
		return jsonName
	}
	return lowerFirstFieldName(fieldName)
}

func swiftPropertyName(fieldName, jsonName string) string {
	if isIdentifier(jsonName) {
		return jsonName
	}
	return lowerFirstFieldName(fieldName)
}

func lowerFirstFieldName(fieldName string) string {
	if fieldName == "" {
		return "value"
	}
	return strings.ToLower(fieldName[:1]) + fieldName[1:]
}

// needsSerialName returns true when the JSON name contains a run of two or
// more consecutive uppercase ASCII letters (e.g. "repoURL", "sessionID",
// "costUSD", "durationAPIMs"). Kotlin properties use these names as-is, but
// kotlinx.serialization would mangle them without an explicit @SerialName.
func needsSerialName(name string) bool {
	consecutive := 0
	for _, r := range name {
		if unicode.IsUpper(r) {
			consecutive++
			if consecutive >= 2 {
				return true
			}
		} else {
			consecutive = 0
		}
	}
	return false
}

// parseJSONTag splits a json struct tag value into name and options.
func parseJSONTag(tag string) (name string, opts []string) {
	name, rest, ok := strings.Cut(tag, ",")
	if !ok || rest == "" {
		return name, nil
	}
	return name, strings.Split(rest, ",")
}

// writeFieldDecl writes a single "val name: Type" (with optional "? = null").
func writeFieldDecl(b *strings.Builder, f *kotlinField) {
	if f.optional {
		b.WriteString("@kotlinx.serialization.EncodeDefault(kotlinx.serialization.EncodeDefault.Mode.NEVER) ")
	}
	if f.presence {
		fmt.Fprintf(b, "val %s: JSONPresence<%s> = JSONPresence.Missing", f.ktName, f.ktType)
		return
	}
	fmt.Fprintf(b, "val %s: %s", f.ktName, f.ktType)
	if f.nullable {
		b.WriteString("?")
	}
	if f.optional {
		b.WriteString(" = null")
	}
}

// fieldsNeedBlock returns true if any field requires its own line.
func fieldsNeedBlock(fields []kotlinField) bool {
	for _, f := range fields {
		if f.serialName != "" || f.doc != "" || f.presence {
			return true
		}
	}
	return false
}

// docGroupRoutes groups routes by categoryName(), preserving first-seen order.
func docGroupRoutes(routes []apispec.Route) []docRouteGroup {
	seen := map[string]int{} // category name → index in result
	var result []docRouteGroup
	for i := range routes {
		r := &routes[i]
		cat := routeCategoryName(r)
		if idx, ok := seen[cat]; ok {
			result[idx].routes = append(result[idx].routes, *r)
		} else {
			seen[cat] = len(result)
			result = append(result, docRouteGroup{name: cat, routes: []apispec.Route{*r}})
		}
	}
	return result
}

// tsObjectKey returns a TypeScript object property key for jsonName.
func tsObjectKey(jsonName string) string {
	if jsonName == "__proto__" {
		return `["__proto__"]`
	}
	if isIdentifier(jsonName) {
		return jsonName
	}
	return fmt.Sprintf("%q", jsonName)
}

// swiftEscapeIdent wraps name in backticks if it is a Swift reserved word.
func swiftEscapeIdent(name string) string {
	if _, ok := swiftReservedWords[name]; ok {
		return "`" + name + "`"
	}
	return name
}

