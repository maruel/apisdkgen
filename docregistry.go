func (d *docRegistry[C]) goTypeToKotlin(t reflect.Type) (string, error) {
	return d.goTypeToKotlinValue(t, false)
}

func (d *docRegistry[C]) goTypeToKotlinValue(t reflect.Type, nullable bool) (string, error) {
	if t.Kind() == reflect.Pointer {
		inner, err := d.goTypeToKotlinValue(t.Elem(), true)
		if err != nil {
			return "", err
		}
		if nullable && !strings.HasSuffix(inner, "?") {
			inner += "?"
		}
		return inner, nil
	}
	if nullable && (t.Kind() == reflect.Map || t.Kind() == reflect.Slice) {
		inner, err := d.goTypeToKotlinValue(t, false)
		if err != nil {
			return "", err
		}
		return inner + "?", nil
	}

	// Special cases.
	if m := lookupSpecial(d.cfg, t); m != nil {
		return m.KTType, nil
	}
	if jsonByteSlice(t) {
		return "ByteArray", nil
	}

	// Named string aliases (Harness, EventKind).
	if _, ok := d.aliasNames[t.Name()]; ok {
		return t.Name(), nil
	}

	switch t.Kind() {
	case reflect.String:
		return "String", nil
	case reflect.Int:
		return "Int", nil
	case reflect.Int32:
		return "Int", nil
	case reflect.Int64:
		return "Long", nil
	case reflect.Uint64:
		return "Long", nil // JSON numbers; unsigned semantics not enforced at wire level.
	case reflect.Float64:
		return "Double", nil
	case reflect.Bool:
		return "Boolean", nil
	case reflect.Slice:
		if isSDKPkg(d.cfg, t.PkgPath()) {
			return t.Name(), nil // Named slice.
		}
		e, err := d.goTypeToKotlinValue(t.Elem(), true)
		if err != nil {
			return "", err
		}
		return "List<" + e + ">", nil
	case reflect.Map:
		if isSDKPkg(d.cfg, t.PkgPath()) {
			return t.Name(), nil
		}
		k, err := d.goTypeToKotlin(t.Key())
		if err != nil {
			return "", err
		}
		v, err := d.goTypeToKotlinValue(t.Elem(), true)
		if err != nil {
			return "", err
		}
		return "Map<" + k + ", " + v + ">", nil
	case reflect.Struct:
		return t.Name(), nil
	default:
		return "", fmt.Errorf("goTypeToKotlin: unhandled kind %s for %s", t.Kind(), t)
	}
}

// parseStructFields extracts kotlinField entries from a reflect.Type.
func (d *docRegistry[C]) parseStructFields(t reflect.Type) ([]kotlinField, error) {
	selected, err := jsonFields(d.cfg, t)
	if err != nil {
		return nil, err
	}
	fields := make([]kotlinField, 0, len(selected))
	names := make(map[string]struct{}, len(selected))
	for _, f := range selected {
		sf := f.field
		jsonName, opts := parseJSONTag(sf.Tag.Get("json"))
		if jsonName == "" {
			jsonName = sf.Name
		}
		omit := jsonOmittable(sf.Type, opts)

		ft := sf.Type
		ktType, err := d.goTypeToKotlin(ft)
		if err != nil {
			return nil, fmt.Errorf("%s.%s: %w", t.Name(), jsonName, err)
		}
		nullable := omit || jsonNilable(ft)
		if base, ok := strings.CutSuffix(ktType, "?"); ok {
			ktType = base
			nullable = true
		}

		ktName := kotlinPropertyName(sf.Name, jsonName)
		if !isIdentifier(ktName) {
			return nil, fmt.Errorf("invalid generated Kotlin property name %q for %s.%s", ktName, t, sf.Name)
		}
		if _, ok := names[ktName]; ok {
			return nil, fmt.Errorf("duplicate generated Kotlin property name %q in %s", ktName, t)
		}
		names[ktName] = struct{}{}
		sn := ""
		if ktName != jsonName || needsSerialName(jsonName) {
			sn = jsonName
		}

		doc := ""
		if fdocs, ok := d.fieldDoc[f.owner.Name()]; ok {
			doc = fdocs[sf.Name]
		}

		fields = append(fields, kotlinField{
			jsonName:   jsonName,
			ktName:     ktName,
			ktType:     ktType,
			nullable:   nullable,
			optional:   omit,
			presence:   jsonThreeState(d.cfg, ft, opts),
			serialName: sn,
			doc:        doc,
		})
	}
	return fields, nil
}

// emitKotlinStruct writes a @Serializable Kotlin DTO class to b.
func (d *docRegistry[C]) emitKotlinStruct(b *strings.Builder, t reflect.Type) error {
	return d.emitKotlinStructVariant(b, t, false)
}

func (d *docRegistry[C]) emitKotlinStructVariant(b *strings.Builder, t reflect.Type, query bool) error {
	if doc := d.typeDoc[t.Name()]; doc != "" {
		b.WriteString(formatBlockDoc(doc, ""))
	}
	fields, err := d.parseStructFields(t)
	if err != nil {
		return err
	}
	name := t.Name()
	if query {
		name += "Query"
		selected, err := jsonFields(d.cfg, t)
		if err != nil {
			return err
		}
		for i := range fields {
			_, opts := parseJSONTag(selected[i].field.Tag.Get("json"))
			if selected[i].field.Type.Kind() == reflect.Pointer || slices.Contains(opts, "omitempty") || slices.Contains(opts, "omitzero") {
				fields[i].nullable, fields[i].optional, fields[i].presence = true, true, false
			}
		}
	}

	if len(fields) == 0 {
		b.WriteString("@Serializable\n")
		fmt.Fprintf(b, "class %s\n", name)
		return nil
	}

	// Compact single-line form for structs with ≤2 fields and no field metadata.
	if len(fields) <= 2 && !fieldsNeedBlock(fields) {
		b.WriteString("@Serializable\n")
		fmt.Fprintf(b, "data class %s(", name)
		for i := range fields {
			if i > 0 {
				b.WriteString(", ")
			}
			writeFieldDecl(b, &fields[i])
		}
		b.WriteString(")\n")
		return nil
	}

	b.WriteString("@Serializable\n")
	fmt.Fprintf(b, "data class %s(\n", name)
	for i := range fields {
		f := &fields[i]
		if f.doc != "" {
			b.WriteString(formatBlockDoc(f.doc, "    "))
		}
		b.WriteString("    ")
		if f.serialName != "" {
			fmt.Fprintf(b, "@SerialName(%s) ", kotlinStringLiteral(f.serialName))
		}
		writeFieldDecl(b, f)
		b.WriteString(",\n")
	}
	b.WriteString(")\n")
	return nil
}

